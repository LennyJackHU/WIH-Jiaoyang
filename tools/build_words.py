#!/usr/bin/env python3
"""Filter data/words_raw.txt into src/words.h (PROGMEM table, flash-resident)."""
import re
import sys

SRC = "data/words_raw.txt"
DST_H = "src/words.h"
DST_CPP = "src/words.cpp"
MAX_WORDS = 2000
MIN_LEN, MAX_LEN = 3, 12

words = []
seen = set()
with open(SRC, encoding="utf-8") as f:
    for line in f:
        w = line.strip().lower()
        if not re.fullmatch(r"[a-z]+", w):
            continue
        if not (MIN_LEN <= len(w) <= MAX_LEN):
            continue
        if w in seen:
            continue
        seen.add(w)
        words.append(w)
        if len(words) >= MAX_WORDS:
            break

if len(words) < MAX_WORDS:
    sys.exit(f"only {len(words)} words after filtering, source too small")

with open(DST_H, "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n")
    f.write("// Generated by tools/build_words.py from data/words_raw.txt - do not edit.\n\n")
    f.write(f"#define WORD_COUNT {len(words)}\n\n")
    f.write("extern const char* const WORDS[WORD_COUNT];\n")

with open(DST_CPP, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/build_words.py from data/words_raw.txt - do not edit.\n")
    f.write('#include "words.h"\n\n')
    f.write("const char* const WORDS[WORD_COUNT] = {\n")
    for w in words:
        f.write(f'    "{w}",\n')
    f.write("};\n")

print(f"wrote {DST_H} + {DST_CPP}: {len(words)} words")
